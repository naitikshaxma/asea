#!/usr/bin/env node
// Creates the ASEA GitHub App through GitHub's official manifest flow and
// stores its credentials in .asea/github-app.env (git-ignored, mode 0600).
// No secret is printed. You confirm the "Create GitHub App" step on github.com.
//
// Usage: node scripts/github/create-app.mjs [--name "ASEA <owner>"] [--web-url http://localhost:5173]
//   --web-url  PUBLIC_WEB_URL of the web app; the OAuth callback is <web-url>/settings
//   --webhook-url  public HTTPS webhook URL (<PUBLIC_WEB_URL>/api/v1/webhooks/github). Without it the
//                  App is created with its webhook inactive and no event subscriptions.
//
// Permissions follow docs/development.md: contents write, pull requests write,
// checks/statuses/metadata read. The App is private; install it only on the
// repositories you intend.
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import http from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, '.asea', 'github-app.env');
const arg = (name, fallback) => {
  const index = process.argv.indexOf(name);
  return index > 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
};
const webUrl = arg('--web-url', 'http://localhost:5173').replace(/\/$/, '');
const webhookUrl = arg('--webhook-url', null);
const name = arg('--name', 'ASEA naitikshaxma');

if (fs.existsSync(OUT)) {
  console.error(`${path.relative(ROOT, OUT)} already exists; refusing to overwrite it. Move it aside to create another App.`);
  process.exit(1);
}
if (webhookUrl && !/^https:\/\//.test(webhookUrl)) {
  console.error('--webhook-url must be a public https:// URL.');
  process.exit(1);
}

const state = randomBytes(24).toString('hex');
const server = http.createServer();
await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
const local = `http://127.0.0.1:${server.address().port}`;

const manifest = {
  name,
  url: 'https://github.com/naitikshaxma/asea',
  description: 'Autonomous Software Engineering Assistant: verified patch publication and CI sync.',
  public: false,
  redirect_url: `${local}/created`,
  callback_urls: [`${webUrl}/settings`],
  request_oauth_on_install: true,
  default_permissions: { contents: 'write', pull_requests: 'write', checks: 'read', statuses: 'read', metadata: 'read' },
  ...(webhookUrl ? {
    hook_attributes: { url: webhookUrl, active: true },
    default_events: ['pull_request', 'check_run', 'check_suite', 'status'],
  } : {}),
};

const escape = (value) => value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
server.on('request', async (req, res) => {
  const url = new URL(req.url, local);
  if (url.pathname === '/') {
    res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
    res.end(`<!doctype html><meta charset="utf-8"><title>Create ASEA GitHub App</title>
<form method="post" action="https://github.com/settings/apps/new?state=${state}">
<input type="hidden" name="manifest" value="${escape(JSON.stringify(manifest))}">
<p>This submits the ASEA App manifest to GitHub. Review the settings there and click <b>Create GitHub App</b>.</p>
<button type="submit">Continue to GitHub</button></form>`);
    return;
  }
  if (url.pathname !== '/created') { res.writeHead(404); res.end(); return; }
  const code = url.searchParams.get('code');
  if (url.searchParams.get('state') !== state || !code || !/^[A-Za-z0-9_-]{8,128}$/.test(code)) {
    res.writeHead(400, { 'Content-Type': 'text/plain' }); res.end('State mismatch or missing code; nothing was saved.');
    return;
  }
  try {
    const conversion = await fetch(`https://api.github.com/app-manifests/${code}/conversions`, {
      method: 'POST', headers: { Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28' },
    });
    if (conversion.status !== 201) throw new Error(`GitHub returned ${conversion.status} for the manifest conversion`);
    const app = await conversion.json();
    // A webhook secret is required with the other values; generated here when the
    // App has no webhook yet, to be entered in the App settings when one is enabled.
    const webhookSecret = app.webhook_secret || randomBytes(32).toString('hex');
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, [
      `# Generated by scripts/github/create-app.mjs for GitHub App "${app.slug}". Never commit this file.`,
      `GITHUB_APP_ID=${app.id}`,
      `GITHUB_APP_SLUG=${app.slug}`,
      `GITHUB_APP_CLIENT_ID=${app.client_id}`,
      `GITHUB_APP_CLIENT_SECRET=${app.client_secret}`,
      `GITHUB_APP_PRIVATE_KEY=${String(app.pem).trim().replace(/\r?\n/g, '\\n')}`,
      `# ${app.webhook_secret ? 'Webhook secret set by GitHub.' : 'Webhook inactive: set this secret in the App settings when you add a webhook URL.'}`,
      `GITHUB_APP_WEBHOOK_SECRET=${webhookSecret}`,
      `PUBLIC_WEB_URL=${webUrl}`,
      '',
    ].join('\n'), { mode: 0o600, flag: 'wx' });
    res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
    res.end(`<!doctype html><meta charset="utf-8"><p>GitHub App <b>${escape(app.slug)}</b> was created and its credentials were saved locally. You can close this tab.</p>`);
    console.log(`Created GitHub App "${app.slug}" (id ${app.id}); credentials saved to ${path.relative(ROOT, OUT)} (not printed).`);
  } catch (error) {
    res.writeHead(502, { 'Content-Type': 'text/plain' }); res.end('The App could not be converted; nothing was saved. See the terminal.');
    console.error(`Manifest conversion failed: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  } finally {
    server.close();
  }
});

console.log(`Open ${local}/ in your browser, continue to GitHub, and click "Create GitHub App".`);
console.log(`Callback URL: ${webUrl}/settings · Webhook: ${webhookUrl ?? 'inactive (no public URL given)'}`);
