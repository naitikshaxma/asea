#!/usr/bin/env node
// Runs the full stack (compose.stack.yaml) as a docker compose project.
// Each project gets its own env file under .asea/ (gitignored) holding
// generated secrets and its web port, created on first use.
//
//   node scripts/stack/stack.mjs up      [--project asea] [--port 8080]
//   node scripts/stack/stack.mjs down    [--project asea] [--volumes]
//   node scripts/stack/stack.mjs logs    [--project asea] [service...]
//   node scripts/stack/stack.mjs ps      [--project asea]
import { randomBytes } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const COMPOSE_FILE = path.join(ROOT, 'compose.stack.yaml');
const SECRETS = ['POSTGRES_PASSWORD', 'JWT_SECRET', 'COOKIE_SECRET', 'INTERNAL_SERVICE_TOKEN'];

/** compose.stack.yaml plus any extra files listed in ASEA_COMPOSE_EXTRA (comma-separated, relative to the root). */
export function composeFiles() {
  const extra = (process.env.ASEA_COMPOSE_EXTRA ?? '').split(',').map((f) => f.trim()).filter(Boolean);
  return [COMPOSE_FILE, ...extra.map((f) => path.join(ROOT, f))];
}

function readEnvFile(file) {
  if (!fs.existsSync(file)) return {};
  return Object.fromEntries(
    fs
      .readFileSync(file, 'utf8')
      .split(/\r?\n/)
      .filter((line) => line && !line.startsWith('#') && line.includes('='))
      .map((line) => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1)])
  );
}

/** The project's env file, created with fresh secrets if missing; returns its path and values. */
export function ensureEnvFile(project, { port } = {}) {
  const file = path.join(ROOT, '.asea', `${project}.env`);
  const values = readEnvFile(file);
  for (const key of SECRETS) values[key] ??= randomBytes(24).toString('hex');
  if (port) values.ASEA_WEB_PORT = String(port);
  values.ASEA_WEB_PORT ??= '8080';
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const lines = Object.entries(values).map(([k, v]) => `${k}=${v}`);
  fs.writeFileSync(file, `# Generated by scripts/stack/stack.mjs for compose project "${project}"\n${lines.join('\n')}\n`);
  return { file, values };
}

/** Runs `docker compose` for the project; returns the exit code (or stdout with capture). */
export function compose(project, args, { capture = false, input } = {}) {
  const { file } = ensureEnvFile(project);
  const result = spawnSync(
    'docker',
    ['compose', '-p', project, ...composeFiles().flatMap((f) => ['-f', f]), '--env-file', file, ...args],
    { cwd: ROOT, stdio: capture ? ['pipe', 'pipe', 'inherit'] : 'inherit', encoding: 'utf8', input }
  );
  if (capture) {
    if (result.status !== 0) throw new Error(`docker compose ${args.join(' ')} exited with ${result.status}`);
    return result.stdout;
  }
  return result.status ?? 1;
}

export function stackUp(project, { port } = {}) {
  const { values } = ensureEnvFile(project, { port });
  const status = compose(project, ['up', '-d', '--build', '--wait', '--wait-timeout', '600']);
  return { status, url: `http://localhost:${values.ASEA_WEB_PORT}` };
}

function parseArgs(argv) {
  const opts = { project: 'asea', rest: [] };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--project') opts.project = argv[++i];
    else if (argv[i] === '--port') opts.port = Number(argv[++i]);
    else if (argv[i] === '--volumes') opts.volumes = true;
    else opts.rest.push(argv[i]);
  }
  return opts;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [command, ...argv] = process.argv.slice(2);
  const opts = parseArgs(argv);
  let status = 0;
  if (command === 'up') {
    const up = stackUp(opts.project, { port: opts.port });
    status = up.status;
    if (status === 0) console.log(`\nASEA is running at ${up.url}`);
  } else if (command === 'down') {
    status = compose(opts.project, ['down', ...(opts.volumes ? ['-v'] : [])]);
  } else if (command === 'logs') {
    status = compose(opts.project, ['logs', '--tail', '200', ...opts.rest]);
  } else if (command === 'ps') {
    status = compose(opts.project, ['ps']);
  } else {
    console.error('Usage: node scripts/stack/stack.mjs <up|down|logs|ps> [--project name] [--port n] [--volumes]');
    status = 2;
  }
  process.exit(status);
}
